export const UI: Record<Lang, Record<UiKey, string>> = { zh, en };

export function t(lang: Lang, key: UiKey, vars: Record<string, string | number> = {}): string {
	return UI[lang][key].replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

/** Map Starlight's BCP-47 tag to our short language code. */
export function toLang(tag: string | undefined): Lang {
	return tag && tag.toLowerCase().startsWith('en') ? 'en' : 'zh';
}
